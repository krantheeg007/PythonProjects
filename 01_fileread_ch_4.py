"""### **2.2 The `safe_ratio` helper**"""

def safe_ratio(numerator: str, denominator: str) -> float | str:
    """Return numerator/denominator, or '' if invalid (zero division, bad type)."""
    try:
        num = float(numerator)
        den = float(denominator)
        if den == 0:
            return ""
        return round(num / den, 6)
    except (TypeError, ValueError):
        return ""

# Quick test
print(safe_ratio("2850.50", "3.2"))   # expected: 890.78125
print(safe_ratio("100", "0"))         # expected: ''
print(safe_ratio("abc", "3"))         # expected: ''

