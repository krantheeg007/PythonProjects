"""### **Exercise 1: Which stock has the highest P/E ratio? What does that imply?**"""

highest_pe_stock = None
max_pe_ratio = -1

for row in rows:
    pe_ratio = row.get('pe_ratio')
    if pe_ratio and isinstance(pe_ratio, (int, float)) and pe_ratio > max_pe_ratio:
        max_pe_ratio = pe_ratio
        highest_pe_stock = row['ticker']

