"""### **Exercise 2: Add a `dividend_yield` column**"""

for row in rows:
    try:
        # As per the prompt: dividend = price * 0.02 and yield = dividend / price
        # This simplifies to dividend_yield = 0.02 (assuming price is not zero)
        # However, it's more robust to calculate based on price if it varies.
        price = float(row['price'])
        if price != 0:
            dividend = price * 0.02
            row['dividend_yield'] = round(dividend / price, 4) # Yield is typically represented as a percentage or a decimal
        else:
            row['dividend_yield'] = ""
    except (ValueError, KeyError):
        row['dividend_yield'] = ""

